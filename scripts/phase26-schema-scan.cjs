// PHASE 26 DIAGNOSTIC: scan all Prisma models and compare against the
// actual SQLite tables in db/custom.db. Reports MISSING tables (tables
// the schema expects but the DB doesn't have) and EXTRA tables (tables
// in the DB not in the schema — usually legacy).
//
// NON-DESTRUCTIVE: read-only inspection.
//
// Run: node scripts/phase26-schema-scan.cjs

const fs = require('fs');
const { DatabaseSync } = require('node:sqlite');

const SCHEMA_PATH = '/home/z/my-project/prisma/schema.prisma';
const DB_PATH = '/home/z/my-project/db/custom.db';

function readModels() {
  const txt = fs.readFileSync(SCHEMA_PATH, 'utf8');
  const models = [];
  // match `model Foo {` blocks
  const re = /\nmodel\s+([A-Z][A-Za-z0-9_]*)\s*\{/g;
  let m;
  while ((m = re.exec(txt)) !== null) {
    models.push(m[1]);
  }
  // also enums are not tables but iterate the same way; we filter on model only.
  return models;
}

function main() {
  const schemaModels = readModels();
  schemaModels.sort();
  console.log('Schema models count: ' + schemaModels.length);

  const db = new DatabaseSync(DB_PATH);
  const tablesRows = db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_prisma_%'").all();
  const dbTables = tablesRows.map(r => r.name).sort();
  console.log('DB tables count: ' + dbTables.length);

  const missing = schemaModels.filter(m => !dbTables.includes(m));
  const extra = dbTables.filter(t => !schemaModels.includes(t));

  console.log('---');
  console.log('MISSING tables (schema expects but DB lacks):');
  for (const m of missing) console.log('  - ' + m);
  if (missing.length === 0) console.log('  (none — schema and DB are in sync)');
  console.log('---');
  console.log('EXTRA tables (DB has but schema lacks — likely legacy/junction tables):');
  for (const e of extra) console.log('  + ' + e);

  // Print CREATE TABLE statement for each missing model so we can build
  // the additive migration script.
  if (missing.length > 0) {
    console.log('---');
    console.log('=== SQL DDL needed for missing tables (will be regenerated by prisma db push) ===');
  }
  db.close();
}

main();
